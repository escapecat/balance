var assert = require('assert/strict'), seed = require('./_strategyseed'), harness = require('./_dom');
var clone = function (v) { return JSON.parse(JSON.stringify(v)); };
var ctx = harness.makeCtx(seed()), S = ctx.Store, St = ctx.Strategy, C = ctx.Config, A = ctx.Allocate, T = ctx.Todos;
var date = '2026-10-30';
var snap = ctx.Ledger.latest(S.get('snapshots')), settings = C.get();
assert.equal(St.schedule(settings, date).configured, true);
assert.equal(St.schedule(settings, date).annualDate, '2027-10-30');
assert.equal(St.schedule(settings, date).annualDue, false);
assert.equal(St.addMonths('2028-08-31', -6), '2028-02-29');
assert.equal(St.addMonths('2027-08-31', -6), '2027-02-28');
C.save({ reviewPolicy: { startDate: '2026-04-30', halfEnabled: true } }); settings = C.get();
assert.equal(St.schedule(settings, date).halfDue, true);
var before = JSON.stringify(S.get('snapshots'));
assert.equal(St.review('half', 'approved', snap, settings, date).ok, false);
assert(St.review('half', 'checked', snap, settings, date).ok);
assert.equal(St.schedule(settings, date).halfDue, false);
assert.equal(St.review('half', 'checked', snap, settings, date).ok, false);
assert.equal(S.get('flows').length, 0); assert.equal(S.get('todos').length, 0);
assert.equal(JSON.stringify(S.get('snapshots')), before);
C.save({ reviewPolicy: { startDate: '2025-10-30', halfEnabled: true } }); settings = C.get();
assert.equal(St.schedule(settings, date).annualDue, true);
assert.equal(St.review('annual', 'approved', snap, settings, date).ok, false, 'Use existing investable cash first');
assert(St.review('annual', 'no-trade', snap, settings, date).ok);
assert.equal(St.schedule(settings, date).annualDate, '2027-10-30');
assert.equal(S.get('flows').length, 0);
// Separate annual scenario, no confirmation => no executable sell/buy todos.
var annualSeed = seed(); annualSeed.settings.reviewPolicy.startDate = '2025-10-30';
annualSeed.snapshots[0].holdings = { '111111': 300000, '222222': 250000, '333333': 400000 };
annualSeed.snapshots[0].cash.c = 50000;
ctx = harness.makeCtx(annualSeed); S = ctx.Store; St = ctx.Strategy; C = ctx.Config; A = ctx.Allocate; T = ctx.Todos;
snap = ctx.Ledger.latest(S.get('snapshots')); settings = C.get();
var preview = A.planAnnual(snap, settings, date);
T.sync(preview, date, date); assert.equal(T.all().length, 0);
assert(St.review('annual', 'approved', snap, settings, date).ok);
T.sync(preview, date, date); assert.equal(T.all().length, 1); assert.equal(T.all()[0].kind, 'sell');
assert.equal(S.get('flows').length, 0, 'Authorization is not a trade');
assert(T.complete(T.all()[0].id, 150000, date).ok);
assert.equal(S.get('flows').length, 1); assert.equal(St.pending(snap).length, 1);
assert.equal(JSON.stringify(S.get('snapshots')), JSON.stringify(annualSeed.snapshots), 'Recording a trade never rewrites the snapshot');
assert.equal(St.review('annual', 'approved', snap, settings, date).ok, false);
C.save({ band: 0.06 }); assert.equal(St.approved(snap, C.get(), date), false);
assert.equal(St.approved(snap, settings, '2026-10-31'), false);
// An unexecuted expired authorization must offer a new review, not lock the user out for a year.
var retry = harness.makeCtx(annualSeed), retrySnap = retry.Ledger.latest(retry.Store.get('snapshots')), retrySettings = retry.Config.get();
assert(retry.Strategy.review('annual', 'approved', retrySnap, retrySettings, date).ok);
retry.Todos.sync(retry.Allocate.planAnnual(retrySnap, retrySettings, date), date, date);
assert.equal(retry.Strategy.schedule(retrySettings, '2026-10-31').annualRecheck, true);
assert(retry.Strategy.review('annual', 'approved', retrySnap, retrySettings, '2026-10-31').ok);
assert.equal(retry.Strategy.schedule(retrySettings, '2026-10-31').annualDate, '2027-10-30', 'Rechecking one cycle must not advance the next calendar twice');
// Same-day plan generations must append transactions, never edit an earlier trade.
ctx = harness.makeCtx(seed()); S = ctx.Store; C = ctx.Config; A = ctx.Allocate; T = ctx.Todos;
snap = ctx.Ledger.latest(S.get('snapshots')); settings = C.get();
var p = A.planMonthly(snap, settings, date); T.sync(p, date, date);
assert(T.complete('buy:111111', 50, date).ok);
var f1 = clone(S.get('flows')[0]);
assert(T.complete('buy:222222', 4000, date).ok, 'Other items of the same frozen budget remain executable');
snap.holdings['111111'] += 50; snap.holdings['222222'] += 4000; snap.cash.c -= 4050;
snap.actionIds = ctx.Actions.capture(date); ctx.Ledger.commit(snap);
var p2 = A.planMonthly(snap, settings, date); T.sync(p2, date, date);
assert(T.complete('buy:111111', 25, date).ok);
assert.equal(S.get('flows').length, 3); assert.equal(JSON.stringify(S.get('flows')[0]), JSON.stringify(f1));
assert(T.undo('buy:111111').ok); assert.equal(S.get('flows').length, 2);
assert.equal(JSON.stringify(S.get('flows')[0]), JSON.stringify(f1), 'Undo only touches the current plan generation');
// Manual pending and settings edits must fence stale plans.
ctx.Actions.add({ date: date, code: '111111', kind: 'buy', amount: 5 });
assert.equal(T.complete('buy:111111', 20, date).ok, false);
assert.equal(ctx.Config.upsertFund({ code: '555555', category: '纳指', trade: { status: 'limited', platform: 'x', checkedOn: date, dailyLimit: -1 } }, true).ok, false);
// v2 upgrade keeps every original balance and flow, holds rather than completes old advice.
var legacy = seed(); legacy.__meta.schema = 2;
legacy.todos = [{ id: 'buy:111111', status: 'partial', actual: 10, target: 100 }];
var upgraded = harness.makeCtx(legacy);
assert.equal(upgraded.Store.SCHEMA, 5);
assert.equal(JSON.stringify(upgraded.Store.get('snapshots')), JSON.stringify(legacy.snapshots));
assert.equal(upgraded.Store.get('todos')[0].status, 'held');
assert.equal(upgraded.Store.get('todos')[0].actual, 10);
assert.equal(upgraded.Store.getRollback().version, 2);
assert.equal(upgraded.Store.inspectImport({ version: upgraded.Store.SCHEMA + 1, data: {} }).ok, false);
var v3 = seed(); v3.__meta.schema = 3;
v3.settings.cashBuckets = { c: { role: 'buffer', settleDays: 99 } };
v3.todos = [{ id: 'buy:111111', code: '111111', kind: 'buy', version: 3, contextKey: 'old-policy', status: 'partial', actual: 10, target: 100 }];
v3.flows = [{ id: 'old1', code: '111111', kind: 'buy', amount: 10, date: date, afterSnapshot: date, todoId: 'buy:111111', planKey: 'old-policy', planDate: date }];
var migrated = harness.makeCtx(v3);
['snapshots', 'flows', 'prefs'].forEach(function (key) { assert.equal(JSON.stringify(migrated.Store.get(key)), JSON.stringify(v3[key])); });
var migratedConfig = clone(migrated.Store.get('settings')); delete migratedConfig.reviewPolicy.startDate; delete migratedConfig.reviewPolicy.source;
assert.equal(JSON.stringify(migratedConfig), JSON.stringify(v3.settings));
assert.equal(migrated.Store.getRollback().version, 3);
assert.equal(migrated.Store.get('todos')[0].status, 'held');
var migratedSnap = migrated.Ledger.latest(migrated.Store.get('snapshots')), migratedSettings = migrated.Config.get();
assert.equal(migrated.Portfolio.investableCash(migratedSnap, migratedSettings), 20000);
assert.equal(migrated.Strategy.pending(migratedSnap).length, 1);
migrated.Todos.sync(migrated.Allocate.planMonthly(migratedSnap, migratedSettings, date), date, date);
assert.equal(migrated.Store.get('todos')[0].status, 'held', 'Old pending trades must fence new-policy suggestions');
var v3annual = clone(annualSeed); v3annual.__meta.schema = 3;
v3annual.settings.reviewPolicy.annualDate = date;
v3annual.prefs.strategyApproval = { contextKey: 'old-policy', date: date, dueDate: date, base: date };
v3annual.todos = [{ id: 'sell:111111', kind: 'sell', contextKey: 'old-policy', status: 'open' }];
var recheck = harness.makeCtx(v3annual);
assert.equal(recheck.Strategy.schedule(recheck.Config.get(), date).annualRecheck, true, 'An unfinished held annual plan must remain reviewable');
var rename = harness.makeCtx(seed()), renameSettings = rename.Config.get(), originalSnapshots = JSON.stringify(rename.Store.get('snapshots'));
assert.equal(rename.Config.upsertFund({ code: '222222', _oldCode: '111111', category: '纳指' }, false).ok, false);
assert(rename.Config.upsertFund({ code: '555555', _oldCode: '111111', category: '纳指', name: '合成新代码' }, false).ok);
assert(rename.Config.allKnown().some(function (f) { return f.code === '111111' && f.category === '纳指'; }));
assert.equal(JSON.stringify(rename.Store.get('snapshots')), originalSnapshots);
console.log('  Strategy ok: explicit calendars, checks not trades, approval fencing, settlement staging, same-day generations and v2 migration');
